-- PROTOTYPE (wayfinder #35): renders fixture planes with lib/map.lua and a walk
-- along their exits, as a Lua chunk the probe embeds. Run from the repo root:
--   luajit prototype/map-pan/gen.lua > prototype/map-pan/planes.lua
package.path = "lib/?.lua;" .. package.path
local map = require("map")
local U = 20

local function walk(rooms, start)
  -- depth-first over same-level exits, stepping back along the way: every
  -- step is a real move between neighbouring cells
  local seen, path = {}, {}
  local function go(id)
    seen[id] = true
    path[#path + 1] = id
    local ws = {}
    for w in pairs(rooms[id].exits or {}) do ws[#ws + 1] = w end
    table.sort(ws)
    for _, w in ipairs(ws) do
      local t = rooms[id].exits[w]
      if rooms[t] and not seen[t] and rooms[t].z == rooms[id].z then
        go(t)
        path[#path + 1] = id
      end
    end
  end
  go(start)
  return path
end

local out = { "-- GENERATED by prototype/map-pan/gen.lua\nPLANES = {" }
for _, f in ipairs({ { "mere", "plane_mereroad", "405" }, { "ochre", "plane_ochrefringe_named", "130" }, { "town", "plane_synthetic_town_rooms", "412" } }) do
  local p = dofile("tests/fixtures/map/" .. f[2] .. ".lua")
  local s = map.new()
  map.map(s, p)
  local h = map.html(s)
  local svg = h:match("(<svg.-</svg>)")
  local vb = svg:match('viewBox="([^"]+)"')
  local inner = svg:match("^<svg[^>]*>(.*)</svg>$")
  local cells = {}
  for _, id in ipairs(walk(p.rooms, f[3])) do
    local r = p.rooms[id]
    cells[#cells + 1] = string.format('{%q,%d,%d,%q}', id, r.x * U, -r.y * U, (p.names or {})[id] or id)
  end
  out[#out + 1] = string.format("  %s = { area = %q, vb = %q, svg = [==[%s]==],\n    path = {%s} },", f[1], p.area, vb, inner, table.concat(cells, ","))
end
out[#out + 1] = "}"
print(table.concat(out, "\n"))
